def extract_keys():
    """扫描 src/ 里所有 tr("...") 的字面量键(去掉 _keys.json 依赖,自包含)。"""
    import ast
    keys = set()
    for f in ("core.py", "ui.py"):
        t = ast.parse((Path(__file__).resolve().parent.parent / "src" / f)
                      .read_text(encoding="utf-8"))
        for node in ast.walk(t):
            if isinstance(node, ast.Call) and getattr(node.func, "id", "") == "tr":
                a = node.args[0] if node.args else None
                if isinstance(a, ast.Constant) and isinstance(a.value, str):
                    keys.add(a.value)
    return keys


def build(catalog: dict, code: str, name: str) -> dict:
    keys = list(extract_keys())
    extra = ["硬件加速 GPU 计划已开启，重启电脑后生效",
             "硬件加速 GPU 计划已关闭，重启电脑后生效",
             "语言已切换为 {0}，重启程序后生效",
             "Ampere（SM86）", "Turing（SM75）", "、", "；",
             "[完成] HAGS：{0}", "[错误] HAGS：{0}",
             "已部署 {0}（Router={1}）",
             "界面语言（切换后重启程序生效）",
             # core.RUNTIMES / core.ENTRIES 的描述字段经 tr(变量) 传入，
             # AST 提取器看不到字面量，必须在此显式登记
             "310.9.16 运行库（上游 0.4.1）",
             "310.9 运行库（上游 0.3.5 兼容）",
             "310.1 运行库（上游 0.3.5 兼容）",
             "默认入口（首选）", "第二选择", "第三选择", "老输入栈游戏",
             "渲染路径（高风险）", "备用入口", "默认入口",
             # core.tier_label() 的返回值经 tr(变量) 传入，同样 AST 看不到
             "0 原厂（最保守）", "1 逐位一致（推荐）",
             "2 更快（有损）", "3 最快（有损）"]
    for k in extra:
        if k not in keys:
            keys.append(k)

    missing = [k for k in keys if k not in catalog]
    orphan = [k for k in catalog if k not in keys and k not in extra]
    if missing:
        raise SystemExit(f"[{code}] 缺 {len(missing)} 条翻译：\n  " + "\n  ".join(missing[:10]))
    if orphan:
        print(f"[{code}] 警告：{len(orphan)} 条多余条目（仍会写入）：", orphan[:5])

    # 占位符一致性校验：译文里的 {n} 必须和原文一致
    import re
    bad = []
    for k in keys:
        a = sorted(re.findall(r"\{(\d+)\}", k))
        b = sorted(re.findall(r"\{(\d+)\}", catalog[k]))
        if a != b:
            bad.append((k, a, b, catalog[k]))
    if bad:
        for k, a, b, v in bad:
            print(f"  占位符不一致: {k} {a} -> {b} : {v}")
        raise SystemExit(f"[{code}] {len(bad)} 条占位符不一致")

    out = {"_meta": {"name": name, "source": "zh_CN"}}
    out.update({k: catalog[k] for k in sorted(keys)})
    p = LANG_DIR / f"{code}.json"
    p.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"[{code}] 写入 {p}（{len(keys)} 条）")
    return out


build(EN, "en_US", "English")
